#!/usr/bin/env node
// Search-quality baseline over the DRBench fixture: each deep-research task's question asked
// through KF's own `GET /search` by the person DRBench set it for, in their own company's
// organization; truth = the task's insight files (its distractors are loaded beside them).
//
//   node fixtures/drbench/search-baseline.mjs [--sample] [--out fixtures/drbench/reports]
//
// Needs every task loaded (`pnpm fixture drbench`). Type = the task's difficulty. The report
// says how many insight files each asker may read at all (classification and grants); a
// deep-research question is a paragraph, so the as-written query rarely matches; the keyword
// query is the fairer number.

import path from 'node:path';
import { readPrevious, scoreQuestions, summarize, writeReport } from '../lib/baseline.mjs';
import { corpusSessions } from '../lib/sessions.mjs';
import { DEFAULT_DATA, HERE, SAMPLE_DIR, companiesIn } from './fixture.mjs';
import { CORPUS, personKey, rank } from './overlay-source.mjs';

const args = process.argv.slice(2);
const sample = args.includes('--sample');
const i = args.indexOf('--out');
const out = i >= 0 ? args[i + 1] : sample ? undefined : path.join(HERE, 'reports');
const dir = sample ? SAMPLE_DIR : DEFAULT_DATA;

const results = [];
let documents = 0;
for (const c of await companiesIn(dir)) {
  documents += c.documents.length;
  const byKey = new Map(c.documents.map((d) => [d.key, d]));
  const { sessionOf, docOfArtifact } = await corpusSessions(
    `${CORPUS}-${c.company.slug}`,
    c.people,
    { personasCorpus: CORPUS },
  );
  const questions = c.tasks.map((t) => {
    const asker = c.people.find((p) => p.key === personKey(t.asker.name));
    const truth = t.files.filter((k) => byKey.get(k)?.qa_type === 'insight');
    return {
      id: t.task,
      type: t.difficulty ?? 'unknown',
      asker: asker.key,
      question: t.question,
      truth,
      readable: truth.filter((k) => {
        const d = byKey.get(k);
        return (
          rank(d.classification) <= rank(asker.clearance) &&
          (rank(d.classification) <= rank(asker.ceiling) || d.readers.includes(asker.key))
        );
      }).length,
    };
  });
  for (const r of await scoreQuestions(questions, {
    sessionOf,
    docOf: (id) => docOfArtifact.get(id),
  }))
    results.push({ ...r, company: c.name });
}
const summary = summarize(results);
if (out !== undefined) {
  await writeReport(out, {
    title: 'DRBench search baseline — recall@10',
    intro: [
      `Generated by \`node fixtures/drbench/search-baseline.mjs\` against every task (${documents} files`,
      'in three organizations). Each task’s question is asked through `GET /search` by its own',
      'persona, in their own company; truth is the task’s insight files. Do not edit by hand.',
    ],
    results,
    summary,
    previous: await readPrevious(path.join(HERE, 'reports', 'search-baseline.2026-09-25.json')),
  });
}
process.stdout.write(`${JSON.stringify(summary.overall)}\n`);
