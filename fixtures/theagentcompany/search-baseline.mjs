#!/usr/bin/env node
// Search-quality baseline over the TheAgentCompany fixture. The benchmark's tasks are work, not
// questions; the ones that name a file on the drive become retrieval questions: the task's text
// is the query, the files it names are the truth (a file named by its path under Documents/, or
// by a file name of at least six characters that occurs once in the drive).
//
//   node fixtures/theagentcompany/search-baseline.mjs [--as <person key>] [--out <dir>]
//
// Needs the drive loaded (`pnpm fixture theagentcompany`) and the benchmark's repository under
// <corpus>/repo-direct (workspaces/tasks/*/task.md). Asked as the CTO (reads everything) unless
// --as names somebody else. Type = the task's family (admin, hr, finance, ds, sde, pm, …).

import { existsSync } from 'node:fs';
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { readPrevious, scoreQuestions, summarize, writeReport } from '../lib/baseline.mjs';
import { corpusSessions } from '../lib/sessions.mjs';
import { DEFAULT_DATA, HERE, documentsIn } from './fixture.mjs';
import { CORPUS, FOUNDER, PEOPLE, rank } from './overlay-source.mjs';

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : fallback;
};
const asker = flag('--as', FOUNDER);
const out = flag('--out', path.join(HERE, 'reports'));
const person = PEOPLE.find((p) => p.key === asker);
const documents = await documentsIn(DEFAULT_DATA);
const byBase = new Map();
for (const d of documents) {
  const base = path.basename(d.path).toLowerCase();
  byBase.set(base, [...(byBase.get(base) ?? []), d]);
}

/** The drive files a task's text names. */
export function namedFiles(text) {
  const lower = text.toLowerCase();
  const found = new Set();
  for (const d of documents) {
    const rel = d.path.toLowerCase();
    const base = path.basename(rel);
    if (lower.includes(rel) || lower.includes(rel.replace(/^documents\//, ''))) found.add(d.key);
    else if (base.length >= 6 && byBase.get(base).length === 1 && lower.includes(base))
      found.add(d.key);
  }
  return [...found].sort();
}

const tasksDir = path.join(DEFAULT_DATA, 'repo-direct', 'workspaces', 'tasks');
const questions = [];
for (const task of (await readdir(tasksDir)).sort()) {
  const file = path.join(tasksDir, task, 'task.md');
  if (!existsSync(file)) continue;
  const text = await readFile(file, 'utf8');
  const truth = namedFiles(text);
  if (truth.length === 0) continue;
  const byKey = new Map(documents.map((d) => [d.key, d]));
  questions.push({
    id: task,
    type: task.split('-')[0],
    asker,
    question: text.replace(/\s+/g, ' ').trim(),
    truth,
    readable: truth.filter((k) => {
      const d = byKey.get(k);
      return (
        rank(d.classification) <= rank(person.clearance) &&
        (rank(d.classification) <= rank(person.ceiling) || d.readers.includes(person.key))
      );
    }).length,
  });
}
const { sessionOf, docOfArtifact } = await corpusSessions(CORPUS, PEOPLE);
const results = await scoreQuestions(questions, {
  sessionOf,
  docOf: (id) => docOfArtifact.get(id),
});
const summary = summarize(results);
await writeReport(out, {
  title: 'TheAgentCompany search baseline — recall@10',
  intro: [
    'Generated by `node fixtures/theagentcompany/search-baseline.mjs` against the whole drive',
    `(${documents.length} files): every benchmark task that names a drive file, its task text asked through`,
    `\`GET /search\` as ${person.name} (${person.title}; clearance ${person.clearance}). Truth: the files the`,
    'task names. The as-written query is the whole task statement (the first 512 characters), so a',
    'file matches only when it holds half of what that statement says. Do not edit by hand; re-run it.',
  ],
  results,
  summary,
  previous: await readPrevious(path.join(HERE, 'reports', 'search-baseline.2026-09-25.json')),
});
process.stdout.write(`${JSON.stringify(summary.overall)}\n`);
