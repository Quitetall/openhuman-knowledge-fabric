/**
 * An archive written before a later migration added a column to a section that already existed
 * still restores, and restores that column as the migration gave rows that predated it (SAS
 * §100.32, KF-SAS-RQ-104, RQ-248).
 *
 * `deliverable-upconversion.test.ts` cuts old archives by removing SECTIONS. That leaves the other
 * half of an old archive's shape untested: the COLUMNS later migrations added to tables whose
 * sections it does carry. The importer inserts the columns a row names, so a missing column takes
 * the column default — right when the migration gave existing rows that default or left them
 * null, wrong when it backfilled something else or declared the column NOT NULL with no default.
 *
 * This file does two things:
 *
 *   1. Enumerates, from `database/migrations/`, every column added to an exported table by a
 *      migration after the one that created the table and after the format went to 2, and requires each to be classified below
 *      by what an archive without it restores as — exhaustively in both directions, so a new
 *      `add column` on an exported table fails here until somebody says what an older archive
 *      does with it.
 *   2. Exports a populated database, removes every reverted column whose section has rows,
 *      restores the result into a fresh database, exports again, and requires every file to come
 *      back as it went out except those columns — and those to hold their classified value.
 *
 * What it does not cover: a column added in a migration whose statement this parser does not read
 * (`alter table ... add column` is the only form the repository uses; a new spelling would be
 * missed, and the count assertion below is the check that the parse found anything); the
 * `label` and `upconverted` columns, whose old values are formats rather than defaults and are
 * restored by the importer under tests of their own; an archive lacking a column AND carrying
 * rows a later migration made possible (it restores every reverted column at once, which is a
 * superset of any one era's shape and not a reproduction of one); and sections the fixture leaves
 * empty, which carry no column names to revert — named in EMPTY_IN_FIXTURE so that list is checked
 * too.
 */

