/** Sections with reverted columns that this fixture leaves empty: nothing to revert in them. */
const EMPTY_IN_FIXTURE = ['backup-copies', 'document-publication-targets', 'object-verifications'];

/** `section.column` for every `add column` on an exported table after the table's creation. */
function addedColumns(): string[] {
  const sectionsOf = new Map<string, string[]>();
  for (const [section, table] of Object.entries(IMPORT_TARGETS)) {
    sectionsOf.set(table, [...(sectionsOf.get(table) ?? []), section]);
  }
  const files = readdirSync(MIGRATIONS)
    .filter((name) => name.endsWith('.sql'))
    .sort();
  const up = (name: string): string =>
    readFileSync(join(MIGRATIONS, name), 'utf8')
      .split('-- migrate:down')[0]!
      .replace(/--[^\n]*/g, '');
  const createdIn = new Map<string, string>();
  for (const name of files) {
    for (const match of up(name).matchAll(
      /create\s+table\s+(?:if\s+not\s+exists\s+)?([a-z_]+\.[a-z_0-9]+)/gi,
    )) {
      if (!createdIn.has(match[1]!)) createdIn.set(match[1]!, name);
    }
  }
  const found = new Set<string>();
  for (const name of files) {
    for (const statement of up(name).matchAll(
      /alter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?([a-z_]+\.[a-z_0-9]+)\s+([\s\S]*?);/gi,
    )) {
      const table = statement[1]!;
      const created = createdIn.get(table);
      if (created === undefined || created >= name || name <= FORMAT_2_LAST_MIGRATION) continue;
      for (const column of statement[2]!.matchAll(
        /add\s+column\s+(?:if\s+not\s+exists\s+)?([a-z_0-9]+)/gi,
      )) {
        for (const section of sectionsOf.get(table) ?? []) found.add(`${section}.${column[1]!}`);
      }
    }
  }
  return [...found].sort();
}

describe('every column added to an exported section is classified (SAS §100.32)', () => {
  it('finds the added columns at all (non-vacuous)', () => {
    expect(addedColumns().length).toBeGreaterThan(20);
    expect(addedColumns()).toContain('role-assignments.classification_ceiling');
  });

  it('classifies exactly the columns the migrations added, in both directions', () => {
    expect(addedColumns()).toEqual(Object.keys(REVERTED_COLUMNS).sort());
  });

  it('would report a planted add column on an exported table', () => {
    // The enumeration is what makes the table exhaustive; a parse that found nothing new would
    // pass the equality above vacuously after the next migration. Plant one in memory.
    const planted = [...addedColumns(), 'people.planted_column'].sort();
    expect(planted).not.toEqual(Object.keys(REVERTED_COLUMNS).sort());
  });
});

let h: Harness;
let f: Fixtures;
let pkg: ExportPackage;

type JsonRow = Record<string, unknown>;

function rowsOf(p: ExportPackage, name: string): JsonRow[] {
  const file = p.files.find((entry) => entry.path === `${name}.json`);
  if (file === undefined) throw new Error(`export has no ${name}.json`);
  return JSON.parse(file.content) as JsonRow[];
}

function sign(p: ExportPackage): ExportPackage {
  return signExportPackage(p, { keyId: KEY_ID, privateKey: KEY.privateKey });
}

/** Rewrite some sections' rows and sign again; the result must verify. */
function repack(base: ExportPackage, changes: ReadonlyMap<string, JsonRow[]>): ExportPackage {
  const files = base.files
    .filter((x) => x.path !== 'manifest.json' && x.path !== EXPORT_MANIFEST_SIGNATURE_PATH)
    .map((x) =>
      changes.has(x.path) ? { path: x.path, content: `${canonicalize(changes.get(x.path))}\n` } : x,
    );
  const manifest: ExportManifest = {
    ...base.manifest,
    database_snapshot_sha256: recomputeDatabaseSnapshotDigest(files, new Set()),
    files: files.map((file) => {
      const bytes = Buffer.from(file.content, 'utf8');
      return { path: file.path, size_bytes: bytes.length, sha256: digestBytes(bytes) };
    }),
  };
  const result = sign({
    files: [...files, { path: 'manifest.json', content: `${canonicalize(manifest)}\n` }],
    manifest,
  });
  expect(verifyExport(result, VERIFICATION)).toEqual([]);
  return result;
}

/** The columns this round trip removes: exported, not a label or a shape, by section. */
function revertible(): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const [key, restores] of Object.entries(REVERTED_COLUMNS)) {
    if (!['null', 'default', 'derived'].includes(restores.kind)) continue;
    if (restores.kind === 'default' && restores.notRoundTripped !== undefined) continue;
    const [section, column] = key.split('.') as [string, string];
    out.set(section, [...(out.get(section) ?? []), column]);
  }
  return out;
}

beforeAll(async () => {
  h = await startHarness();
  f = await seedFixtures(h.adminPool);
  const execute = createFabricDispatcher(
    h.pool,
    createDocumentActionAtoms({
      store: new InMemoryObjectStore(),
      parser: {
        async parse() {
          return undefined;
        },
      },
    }),
  );
  // A master record and its items, so the derived corpus digest and the defaulted content
  // payload are exercised against rows rather than an empty section.
  await execute({
    actionType: 'compile_master_record',
    actorId: f.performerId,
    actingRoleId: f.performerRoleId,
    organizationId: f.organizationId,
    maxClassification: 'restricted',
    targetIds: [f.performerId],
    idempotencyKey: randomUUID(),
  });
  pkg = sign(await withTransaction(h.adminPool, (tx) => createExport(tx)));
}, 240_000);

afterAll(async () => {
  await h?.stop();
});

describe('an archive without the columns later migrations added restores (SAS §100.32)', () => {
  it('exports every column it classifies as carried', () => {
    for (const [section, columns] of revertible()) {
      const rows = rowsOf(pkg, section);
      if (EMPTY_IN_FIXTURE.includes(section)) {
        expect(rows, `${section} is listed as empty in the fixture`).toEqual([]);
        continue;
      }
      expect(rows.length, `${section} has no rows to revert`).toBeGreaterThan(0);
      for (const column of columns) {
        expect(Object.keys(rows[0]!), `${section}.json does not carry ${column}`).toContain(column);
      }
    }
  });

  it('restores each as the migration left older rows, and everything else unchanged', async () => {
    const reverted = new Map<string, JsonRow[]>();
    for (const [section, columns] of revertible()) {
      if (EMPTY_IN_FIXTURE.includes(section)) continue;
      reverted.set(
        `${section}.json`,
        rowsOf(pkg, section).map((row) =>
          Object.fromEntries(Object.entries(row).filter(([column]) => !columns.includes(column))),
        ),
      );
    }
    const older = repack(pkg, reverted);
    for (const [path, rows] of reverted) {
      const section = path.replace(/\.json$/, '');
      for (const column of revertible().get(section)!) {
        expect(Object.keys(rows[0]!), `${section} still names ${column}`).not.toContain(column);
      }
    }

    const fresh = await startHarness();
    try {
      await withTransaction(fresh.adminPool, (tx) => importExport(tx, older, VERIFICATION));
      const again = sign(await withTransaction(fresh.adminPool, (tx) => createExport(tx)));
      expect(verifyExport(again, VERIFICATION)).toEqual([]);

      const expected = (section: string, row: JsonRow): JsonRow => {
        const out = { ...row };
        for (const column of revertible().get(section) ?? []) {
          const restores = REVERTED_COLUMNS[`${section}.${column}`]!;
          if (restores.kind === 'null') out[column] = null;
          if (restores.kind === 'default') out[column] = restores.exported;
          // `derived` keeps the value the archive's own exporter would have recorded.
        }
        return out;
      };
      for (const file of pkg.files) {
        if (file.path === 'manifest.json' || file.path === EXPORT_MANIFEST_SIGNATURE_PATH) continue;
        const section = file.path.replace(/\.json$/, '');
        const restored = again.files.find((entry) => entry.path === file.path);
        expect(restored, `${file.path} is missing after the restore`).toBeDefined();
        if (!revertible().has(section) || EMPTY_IN_FIXTURE.includes(section)) {
          expect(restored!.content, `${file.path} differs after the restore`).toBe(file.content);
          continue;
        }
        expect(
          rowsOf(again, section),
          `${section} did not restore its reverted columns as classified`,
        ).toEqual(rowsOf(pkg, section).map((row) => expected(section, row)));
      }
    } finally {
      await fresh.stop();
    }
  }, 300_000);
});
