-- The urgent push reaches each person (ADR 0040 decision 9, KF-SAS-RQ-274; SAS §24B; closes the
-- database half of §100.57).
--
-- Until now the urgent push had one destination: the deployment's alert topic, which belongs to
-- the one person named by KF_NOTIFY_PUSH_PERSON. Everyone else learned of an urgent item from
-- their digest. Two things change here.
--
--   1. A PERSON'S OWN PUSH DESTINATION: `core.push_destination`, per person and organization, an
--      ntfy topic URL sealed to the deployment's notifier key — or none. An ntfy topic URL is a
--      capability: anyone holding it reads and forges what is sent there. So it is never stored,
--      recorded or exported in plaintext. The API seals it (X25519 + HKDF-SHA256 + AES-256-GCM,
--      `@kf/authorization` push-destination.ts) to the public half of a key only the notifier's
--      unit holds, bound to the organization and person it belongs to, BEFORE the act is
--      dispatched, so the ledger's `core.action.parameters` carry the sealed value and nothing
--      else. The database refuses anything that is not a sealed envelope, in every session, an
--      administrator's and a restore's included (KF-NOTIFY-004). Nobody reads it but the person
--      it belongs to (row security) and the notifier's function below, and neither can open it
--      but the notifier. Written only by `set_push_destination` (KF-NOTIFY-003), for the person
--      performing it and never by an agent acting for them (KF-NOTIFY-001, as for a preference).
--      Append-only; the highest revision is in force, and a null `sealed` clears it.
--
--   2. EACH URGENT ITEM, TO EACH PERSON ENTITLED TO SEE IT, AT SEND TIME: `core.urgent_pushes`,
--      replacing `core.urgent_notifications`. One row per item and person: the person's live
--      membership in the organization, their push setting, and — new — whether they may read the
--      item NOW under their grants and clearance (`core.notification_person_reads`, the digest's
--      own test): every target of a proposal, the warrant of a blocker. An item a person cannot
--      read is not returned for them, so it is never pushed to them; the digest still counts what
--      Needs you lists. A title is returned only when the item may leave the host under its
--      organization's provider ceiling (`core.may_leave_host`), exactly as the digest decides;
--      otherwise `disclosed` is false and the title null (KF-SAS-RQ-274). The row carries the
--      person's sealed destination, or null: a person with none is told by the digest (or by the
--      host's alert path, for KF_NOTIFY_PUSH_PERSON, which kf-notify keeps).
--
-- WHAT IS NOT EXPORTED, AND WHY. `core.push_destination` is left out of the preservation export
-- (PRESERVATION_TABLE_EXCLUSIONS): a sealed destination opens only under THIS deployment's notifier
-- key, which a restore target does not hold, and the export's retention is unbounded. The act that
-- set it travels sealed in actions.json; the operational backup (kf_backup) carries the table, so a
-- same-host recovery keeps it. On a new deployment a person sets their destination again.

-- 1. A person's own push destination --------------------------------------------------------------

create table core.push_destination (
  id               uuid primary key default uuidv7(),
  revision         bigint generated by default as identity unique,
  organization_id  uuid not null references org.organization (id) on delete restrict,
  person_id        uuid not null references org.person (id),
  -- kfpd1.<key id>.<ephemeral X25519 public key>.<nonce>.<AES-256-GCM ciphertext and tag>, or
  -- null: no destination. Never a URL (KF-NOTIFY-004, and this check again).
  -- PostgreSQL bounds a regular-expression repeat at 255, so the length is bounded separately: 788
  -- characters is the envelope of a 512-byte URL.
  sealed           text check (
    sealed is null
    or (sealed ~ '^kfpd1\.[0-9a-f]{16}\.[A-Za-z0-9_-]{43}\.[A-Za-z0-9_-]{16}\.[A-Za-z0-9_-]{22,}$'
        and length(sealed) <= 788)),
  set_by_action    uuid not null unique references core.action (id) on delete restrict,
  set_at           timestamptz not null default now()
);

create index push_destination_key
  on core.push_destination (organization_id, person_id, revision desc);

comment on table core.push_destination is
  'A person''s own urgent-push destination per organization (ADR 0040 decision 9, KF-SAS-RQ-274): '
  'an ntfy topic URL sealed to the notifier''s key, never plaintext (KF-NOTIFY-004), or null for '
  'none. Read only by the person and core.urgent_pushes; opened only by kf-notify. Append-only; '
  'written only by set_push_destination (KF-NOTIFY-003), never by an agent (KF-NOTIFY-001). Not '
  'exported: it opens only under this deployment''s key.';

create function core.push_destination_bounded() returns trigger
language plpgsql
security definer
set search_path = pg_catalog, core
as $$
begin
  if tg_op <> 'INSERT' then
    raise exception 'a push destination is superseded by a later one, never % (Law 6)', lower(tg_op)
      using errcode = 'insufficient_privilege';
  end if;
  -- In every session, an administrator's and a restore's included: a capability is never stored
  -- where every reader of a backup could use it.
  if new.sealed is not null and (new.sealed !~
       '^kfpd1\.[0-9a-f]{16}\.[A-Za-z0-9_-]{43}\.[A-Za-z0-9_-]{16}\.[A-Za-z0-9_-]{22,}$'
       or length(new.sealed) > 788) then
    raise exception 'KF-NOTIFY-004: a push destination is stored only sealed to the notifier''s '
      'key, never as a URL (PUT /notification-destination seals it)'
      using errcode = 'check_violation';
  end if;
  if core.session_is_administrator() then
    return new;
  end if;
  if core.current_agent_or_null() is not null then
    raise exception 'KF-NOTIFY-001: how a person is notified is their own setting; agent % acting '
      'for them may not change it', core.current_agent_or_null()
      using errcode = 'check_violation';
  end if;
  if core.current_action_type() is distinct from 'set_push_destination' then
    raise exception 'KF-NOTIFY-003: a push destination is written only by set_push_destination; '
      'this transaction recorded %', coalesce(core.current_action_type(), 'no act')
      using errcode = 'check_violation';
  end if;
  new.revision := nextval(pg_get_serial_sequence('core.push_destination', 'revision'));
  new.organization_id := core.current_organization();
  -- Whose destination it is: the person performing the act, never a person the caller names.
  new.person_id := core.current_actor_or_null();
  new.set_by_action := core.current_action_id();
  new.set_at := now();
  return new;
end
$$;

revoke all on function core.push_destination_bounded() from public;

create trigger push_destination_bounded
  before insert or update or delete on core.push_destination
  for each row execute function core.push_destination_bounded();

create trigger push_destination_guard_context
  before insert on core.push_destination
  for each row execute function core.require_transaction_context();

alter table core.push_destination enable row level security;
alter table core.push_destination force row level security;

-- The person it belongs to, and nobody else on the application's login. No auditor or read-only
-- grant: what is sealed there is a capability, and an auditor learns the setting changed from the
-- act's ledger row.
create policy push_destination_read on core.push_destination
  for select
  using (
    organization_id = (select core.current_organization())
    and person_id = (select core.current_principal_or_null())
  );
create policy push_destination_insert on core.push_destination
  for insert
  with check (
    organization_id = (select core.current_organization())
    and person_id = (select core.current_actor_or_null())
    and set_by_action = (select core.current_action_id())
  );
create policy push_destination_backup_read on core.push_destination
  for select to kf_backup using (true);

revoke all on core.push_destination from public;
grant select, insert on core.push_destination to kf_app;
grant select on core.push_destination to kf_backup;
grant select on sequence core.push_destination_revision_seq to kf_backup;

-- 2. Each urgent item, to each person entitled to see it --------------------------------------------

drop function core.urgent_notifications(timestamptz, uuid);

-- The urgent items that arose after (p_since, p_since_item), one row per item and person to tell,
-- ordered by (arose_at, item_id, person_id):
--
--   proposal_waiting  an institutional act an agent proposed for this person, waiting on them, when
--                     they read every record it targets;
--   blocker_opened    a warrant blocker opened in the organization, for each person holding a live
--                     organization-wide technical_authority assignment there who reads the warrant.
--
-- A person is told only while they hold a live assignment in the organization and have not turned
-- the push off. `disclosed` and `title` follow the digest's rule: a title only when every record
-- it names may leave the host. `destination` is the person's sealed destination, or null.
create function core.urgent_pushes(p_since timestamptz, p_since_item uuid)
returns table (
  organization_id uuid,
  person_id uuid,
  kind text,
  arose_at timestamptz,
  item_id uuid,
  disclosed boolean,
  title text,
  destination text
)
language sql
stable
security definer
set search_path = pg_catalog, core, org, work
as $$
  with since as (
    select p_since as at,
           coalesce(p_since_item, '00000000-0000-0000-0000-000000000000'::uuid) as item
  ),
  proposals as (
    select p.organization_id, p.proposed_for as person_id, 'proposal_waiting'::text as kind,
           p.proposed_at as arose_at, p.id as item_id,
           coalesce((select bool_and(core.notification_person_reads(
                                       p.proposed_for, p.organization_id, o.id, o.classification))
                       from core.object o where o.id = any(p.target_ids)), true)
             and (select count(*) from core.object o where o.id = any(p.target_ids))
                 = cardinality(p.target_ids) as reads,
           coalesce((select bool_and(core.may_leave_host(p.organization_id, o.classification))
                       from core.object o where o.id = any(p.target_ids)), false) as leaves,
           p.action_type || coalesce(': ' || (select string_agg(o.title, '; ' order by o.title)
                                                from core.object o
                                               where o.id = any(p.target_ids)), '') as title
      from core.act_proposal p, since
     where (p.proposed_at, p.id) > (since.at, since.item)
       and not exists (select 1 from core.act_proposal_resolution x where x.proposal_id = p.id)
  ),
  blockers as (
    select warrant_object.organization_id, ra.subject_id as person_id,
           'blocker_opened'::text as kind, b.opened_at as arose_at, b.id as item_id,
           core.notification_person_reads(ra.subject_id, warrant_object.organization_id,
                                          warrant_object.id, warrant_object.classification) as reads,
           core.may_leave_host(warrant_object.organization_id, warrant_object.classification)
             as leaves,
           'Blocked: ' || warrant_object.title as title
      from work.warrant_blocker b
      join core.object warrant_object on warrant_object.id = b.warrant_id
      join org.role_assignment ra
        on ra.role_id = 'technical_authority'
       and ra.scope_id = warrant_object.organization_id
       and ra.valid_from <= now() and (ra.valid_to is null or ra.valid_to > now())
     cross join since
     where (b.opened_at, b.id) > (since.at, since.item)
       and b.resolved_at is null
  ),
  items as (
    select * from proposals
    union all
    select * from blockers
  )
  select i.organization_id, i.person_id, i.kind, i.arose_at, i.item_id,
         i.leaves,
         case when i.leaves then i.title end,
         (select d.sealed from core.push_destination d
           where d.organization_id = i.organization_id and d.person_id = i.person_id
           order by d.revision desc limit 1)
    from items i
   where i.reads
     -- A member now: a live assignment in the organization, as the digest's recipients.
     and exists (select 1 from org.role_assignment ra
                   join core.object ra_object on ra_object.id = ra.id
                  where ra.subject_id = i.person_id
                    and ra_object.organization_id = i.organization_id
                    and ra.valid_from <= now() and (ra.valid_to is null or ra.valid_to > now()))
     and coalesce(
           (select np.push from core.notification_preference np
             where np.organization_id = i.organization_id and np.person_id = i.person_id
             order by np.revision desc limit 1),
           'urgent') = 'urgent'
   order by i.arose_at, i.item_id, i.person_id
$$;

revoke all on function core.urgent_pushes(timestamptz, uuid) from public;
grant execute on function core.urgent_pushes(timestamptz, uuid) to kf_notifier;

comment on role kf_notifier is
  'kf-notify''s login inherits this and nothing else: execute on core.needs_you_digest() and '
  'core.urgent_pushes(timestamptz, uuid). It reads no table; what a notification may say, and to '
  'whom, is decided by those functions (KF-SAS-RQ-274).';

