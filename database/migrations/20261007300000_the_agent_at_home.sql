-- 3. What a notification may say ------------------------------------------------------------------

-- Whether a person may read one record now, as Needs you decides it: a live, unretired clearance in
-- the organization at or above the record's classification, and a live read grant reaching it —
-- organization-wide or on the record, within the grant's ceiling, to the person or to an assignment
-- they hold (enumerateAccessCoverage + coveringGrants in @kf/authorization, applied in SQL).
create function core.notification_person_reads(
  p_person uuid, p_organization uuid, p_object uuid, p_classification text)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, core, org, registry
as $$
  with rank as (select c.rank from registry.classification c where c.id = p_classification)
  select exists (
           select 1
             from org.person_clearance pc
             join registry.classification cleared on cleared.id = pc.max_classification
            where pc.subject_id = p_person
              and pc.organization_id = p_organization
              and pc.valid_from <= now()
              and (pc.valid_to is null or pc.valid_to > now())
              and not exists (select 1 from org.person_clearance_retirement r
                               where r.clearance_id = pc.id)
              and cleared.rank >= (select rank from rank))
     and exists (
           select 1
             from org.effective_access_grant g
             left join registry.classification ceiling on ceiling.id = g.classification_ceiling
            where g.organization_id = p_organization
              and g.capability = 'read'
              and g.scope_object_id in (p_organization, p_object)
              and g.valid_from <= now()
              and (g.valid_to is null or g.valid_to > now())
              and (g.classification_ceiling is null or ceiling.rank >= (select rank from rank))
              and ((g.principal_kind = 'person' and g.principal_id = p_person)
                or (g.principal_kind = 'role_assignment' and exists (
                      select 1 from org.role_assignment ra
                       where ra.id = g.principal_id and ra.subject_id = p_person
                         and ra.valid_from <= now()
                         and (ra.valid_to is null or ra.valid_to > now())))))
$$;

revoke all on function core.notification_person_reads(uuid, uuid, uuid, text) from public;

-- Whether a classification may leave the host under an organization's ceiling.
create function core.may_leave_host(p_organization uuid, p_classification text) returns boolean
language sql
stable
security definer
set search_path = pg_catalog, core, registry
as $$
  select coalesce(
    (select c.rank <= ceiling.rank
       from registry.classification c, registry.classification ceiling
      where c.id = p_classification
        and ceiling.id = core.provider_ceiling_in_force(p_organization)),
    false)
$$;

revoke all on function core.may_leave_host(uuid, text) from public;

-- Every person's Needs you, redacted for a channel the deployment does not control. One row per
-- item. `disclosed` false: no identifier and no title, only that an item of `kind` exists.
--
--   to_verify       unverified records an agent wrote, created by someone else, which the person
--                   reads and may verify (a live technical_authority assignment at the
--                   organization or the record) — the toVerify list of GET /needs-you;
--   awaiting_others unverified records an agent wrote for this person;
--   proposal        institutional acts the person's agents proposed, unanswered. Disclosed as the
--                   act's name and its targets' titles only when every target may leave the host
--                   and the person reads it; the payload and reason are never returned.
--
-- People with no e-mail address, no live assignment in the organization, or the digest turned off
-- are not listed.
create function core.needs_you_digest()
returns table (
  organization_id uuid,
  organization_name text,
  person_id uuid,
  email text,
  kind text,
  disclosed boolean,
  item_id uuid,
  title text
)
language sql
stable
security definer
set search_path = pg_catalog, core, org, registry
as $$
  with recipients as (
    select distinct ra_object.organization_id, p.id as person_id, btrim(p.email) as email
      from org.person p
      join org.role_assignment ra on ra.subject_id = p.id
      join core.object ra_object on ra_object.id = ra.id
     where p.email is not null and p.email ~ '^[^@\s<>]+@[^@\s<>]+$'
       and ra.valid_from <= now() and (ra.valid_to is null or ra.valid_to > now())
       and coalesce(
             (select np.digest from core.notification_preference np
               where np.organization_id = ra_object.organization_id and np.person_id = p.id
               order by np.revision desc limit 1),
             'daily') = 'daily'
  ),
  touched as (
    select distinct on (t.id) t.id, a.organization_id, a.actor_id
      from core.action a
     cross join lateral unnest(a.target_ids) as t(id)
     where a.agent_participation is not null
       and a.action_type not in ('propose_act', 'set_verification_policy',
                                 'resolve_act_proposal', 'compile_master_record')
     order by t.id, a.recorded_at desc
  ),
  unverified as (
    select o.id, o.organization_id, o.classification, o.title, o.created_by
      from touched
      join core.object o on o.id = touched.id and o.organization_id = touched.organization_id
     where o.object_type <> 'organization'
       and not exists (select 1 from core.object_verification v where v.object_id = o.id)
  ),
  record_items as (
    select r.organization_id, r.person_id, r.email,
           case when u.created_by = r.person_id then 'awaiting_others' else 'to_verify' end as kind,
           u.id, u.classification, u.title
      from recipients r
      join unverified u on u.organization_id = r.organization_id
     where core.notification_person_reads(r.person_id, r.organization_id, u.id, u.classification)
       and (u.created_by = r.person_id
            or exists (select 1 from org.role_assignment ra
                         join core.object ra_object on ra_object.id = ra.id
                        where ra.subject_id = r.person_id
                          and ra_object.organization_id = r.organization_id
                          and ra.role_id = 'technical_authority'
                          and ra.scope_id in (r.organization_id, u.id)
                          and ra.valid_from <= now()
                          and (ra.valid_to is null or ra.valid_to > now())))
  ),
  proposal_items as (
    select r.organization_id, r.person_id, r.email, 'proposal'::text as kind, p.id,
           p.action_type,
           (select bool_and(core.may_leave_host(r.organization_id, o.classification)
                            and core.notification_person_reads(r.person_id, r.organization_id,
                                                               o.id, o.classification))
              from core.object o where o.id = any(p.target_ids)) as targets_leave,
           (select string_agg(o.title, '; ' order by o.title)
              from core.object o where o.id = any(p.target_ids)) as target_titles
      from recipients r
      join core.act_proposal p
        on p.organization_id = r.organization_id and p.proposed_for = r.person_id
     where not exists (select 1 from core.act_proposal_resolution x where x.proposal_id = p.id)
  ),
  -- The organization's legal name, under the same rule as any record's title: it is a field of the
  -- organization's own record.
  organization_names as (
    select o.id,
           case when core.may_leave_host(o.id, org_object.classification) then o.legal_name end
             as name
      from org.organization o
      join core.object org_object on org_object.id = o.id
  )
  select i.organization_id, n.name, i.person_id, i.email, i.kind,
         core.may_leave_host(i.organization_id, i.classification),
         case when core.may_leave_host(i.organization_id, i.classification) then i.id end,
         case when core.may_leave_host(i.organization_id, i.classification) then i.title end
    from record_items i
    join organization_names n on n.id = i.organization_id
  union all
  select i.organization_id, n.name, i.person_id, i.email, i.kind,
         coalesce(i.targets_leave, false),
         case when coalesce(i.targets_leave, false) then i.id end,
         case when coalesce(i.targets_leave, false)
              then i.action_type || coalesce(': ' || i.target_titles, '') end
    from proposal_items i
    join organization_names n on n.id = i.organization_id
$$;

revoke all on function core.needs_you_digest() from public;
grant execute on function core.needs_you_digest() to kf_notifier;

-- The urgent items that arose after `p_since`, one row per item and person to tell, and nothing
-- about the item but its kind: a push names no record, no person and no organization.
--
--   proposal_waiting  an institutional act an agent proposed for this person, waiting on them;
--   blocker_opened    a warrant blocker opened in the organization, for each person holding a live
--                     organization-wide technical_authority assignment there: a person is blocked
--                     on the organization, and the organization's authority is who can unblock.
--
-- A failed backup or alert is the third urgent kind; it is pushed by kf-alert@.service, the path
-- every unit's OnFailure= already takes, and is not repeated here.
create function core.urgent_notifications(p_since timestamptz)
returns table (person_id uuid, kind text, arose_at timestamptz)
language sql
stable
security definer
set search_path = pg_catalog, core, org, work
as $$
  select p.proposed_for, 'proposal_waiting'::text, p.proposed_at
    from core.act_proposal p
   -- Compared at millisecond precision: the notifier keeps its boundary as a JavaScript instant.
   where date_trunc('milliseconds', p.proposed_at) > p_since
     and not exists (select 1 from core.act_proposal_resolution x where x.proposal_id = p.id)
     and coalesce(
           (select np.push from core.notification_preference np
             where np.organization_id = p.organization_id and np.person_id = p.proposed_for
             order by np.revision desc limit 1),
           'urgent') = 'urgent'
  union all
  select ra.subject_id, 'blocker_opened'::text, b.opened_at
    from work.warrant_blocker b
    join core.object warrant_object on warrant_object.id = b.warrant_id
    join org.role_assignment ra
      on ra.role_id = 'technical_authority'
     and ra.scope_id = warrant_object.organization_id
     and ra.valid_from <= now() and (ra.valid_to is null or ra.valid_to > now())
   where date_trunc('milliseconds', b.opened_at) > p_since
     and b.resolved_at is null
     and coalesce(
           (select np.push from core.notification_preference np
             where np.organization_id = warrant_object.organization_id
               and np.person_id = ra.subject_id
             order by np.revision desc limit 1),
           'urgent') = 'urgent'
$$;

revoke all on function core.urgent_notifications(timestamptz) from public;
grant execute on function core.urgent_notifications(timestamptz) to kf_notifier;

