create function core.notification_preference_bounded() returns trigger
language plpgsql
security definer
set search_path = pg_catalog, core
as $$
begin
  if tg_op <> 'INSERT' then
    raise exception 'a notification preference is superseded by a later one, never % (Law 6)',
      lower(tg_op)
      using errcode = 'insufficient_privilege';
  end if;
  if core.session_is_administrator() then
    return new;
  end if;
  if core.current_agent_or_null() is not null then
    raise exception 'KF-NOTIFY-001: how a person is notified is their own setting; agent % acting '
      'for them may not change it', core.current_agent_or_null()
      using errcode = 'check_violation';
  end if;
  if core.current_action_type() is distinct from 'set_notification_preference' then
    raise exception 'KF-NOTIFY-002: a notification preference is written only by '
      'set_notification_preference; this transaction recorded %',
      coalesce(core.current_action_type(), 'no act')
      using errcode = 'check_violation';
  end if;
  new.revision := nextval(pg_get_serial_sequence('core.notification_preference', 'revision'));
  new.organization_id := core.current_organization();
  -- Whose setting it is: the person performing the act, never a person the caller names.
  new.person_id := core.current_actor_or_null();
  new.set_by_action := core.current_action_id();
  new.set_at := now();
