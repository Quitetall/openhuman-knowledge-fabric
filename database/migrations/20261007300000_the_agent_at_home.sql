-- 1. Which model may read what --------------------------------------------------------------------

create table core.model_routing_policy (
  id               uuid primary key default uuidv7(),
  revision         bigint generated by default as identity unique,
  organization_id  uuid not null references org.organization (id) on delete restrict,
  -- The highest classification that may leave the host: to a provider's model, or in a
  -- notification. Never confidential or restricted (KF-ROUTE-001, and this check again).
  provider_ceiling text not null check (provider_ceiling in ('none', 'public', 'internal')),
  reason           text not null check (length(btrim(reason)) >= 8),
  set_by           uuid not null references org.person (id),
  set_by_action    uuid not null unique references core.action (id) on delete restrict,
  set_at           timestamptz not null default now()
);

create index model_routing_policy_key on core.model_routing_policy (organization_id, revision desc);

comment on table core.model_routing_policy is
  'The highest classification of content that may leave the host, to a provider''s model or in a '
  'notification, per organization (ADR 0040 decision 8, KF-SAS-RQ-271, RQ-274). none, public or '
  'internal; never confidential or restricted (KF-ROUTE-001). No row means internal. Append-only; '
  'the highest revision is in force. Written only by set_model_routing_policy, an institutional act.';

-- What is in force for one organization: its latest row, else the default. Definer, so the
-- notifier's functions and every reader ask one question with one answer.
create function core.provider_ceiling_in_force(p_organization uuid) returns text
language sql
stable
security definer
set search_path = pg_catalog, core
as $$
  select coalesce(
    (select p.provider_ceiling from core.model_routing_policy p
      where p.organization_id = p_organization
      order by p.revision desc limit 1),
    'internal')
$$;

revoke all on function core.provider_ceiling_in_force(uuid) from public;
grant execute on function core.provider_ceiling_in_force(uuid) to kf_app;

create function core.model_routing_policy_bounded() returns trigger
language plpgsql
security definer
set search_path = pg_catalog, core
as $$
begin
  if tg_op <> 'INSERT' then
    raise exception 'a model routing policy is superseded by a later one, never % (Law 6)', lower(tg_op)
      using errcode = 'insufficient_privilege';
  end if;
  -- In every session, an administrator's and a restore's included: ADR 0040 decision 8 is not an
  -- organization's to change.
  if new.provider_ceiling in ('confidential', 'restricted') then
    raise exception 'KF-ROUTE-001: % content is answered only on the host and never sent to a '
      'provider''s model or in a notification (ADR 0040, KF-SAS-RQ-271)', new.provider_ceiling
      using errcode = 'check_violation';
  end if;
  if core.session_is_administrator() then
    return new;
  end if;
  if core.current_action_type() is distinct from 'set_model_routing_policy' then
    raise exception 'KF-ROUTE-002: a model routing policy is written only by '
      'set_model_routing_policy, an institutional act; this transaction recorded %',
      coalesce(core.current_action_type(), 'no act')
      using errcode = 'check_violation';
  end if;
  new.revision := nextval(pg_get_serial_sequence('core.model_routing_policy', 'revision'));
  new.organization_id := core.current_organization();
  new.set_by := core.current_actor_or_null();
  new.set_by_action := core.current_action_id();
  new.set_at := now();
  return new;
end
$$;

revoke all on function core.model_routing_policy_bounded() from public;

create trigger model_routing_policy_bounded
  before insert or update or delete on core.model_routing_policy
  for each row execute function core.model_routing_policy_bounded();

create trigger model_routing_policy_guard_context
  before insert on core.model_routing_policy
  for each row execute function core.require_transaction_context();

alter table core.model_routing_policy enable row level security;
alter table core.model_routing_policy force row level security;

-- Everyone in the organization may read what may leave it: the answer names its backend, and the
-- reason a question went to the host is not a secret from the person asking.
create policy model_routing_policy_read on core.model_routing_policy
  for select
  using (organization_id = (select core.current_organization()));

create policy model_routing_policy_insert on core.model_routing_policy
  for insert
  with check (
    organization_id = (select core.current_organization())
    and set_by = (select core.current_actor_or_null())
    and set_by_action = (select core.current_action_id())
  );

create policy model_routing_policy_auditor_read on core.model_routing_policy
  for select to kf_auditor using (true);
create policy model_routing_policy_backup_read on core.model_routing_policy
  for select to kf_backup using (true);

revoke all on core.model_routing_policy from public;
grant select, insert on core.model_routing_policy to kf_app;
grant select on core.model_routing_policy to kf_readonly, kf_auditor, kf_backup;
grant select on sequence core.model_routing_policy_revision_seq to kf_backup;

