-- The agent at home (ADR 0040 decisions 7, 8 and 9; SAS §24B, KF-SAS-RQ-271, RQ-272, RQ-274;
-- milestone M4, KF-WAR-0006; closes the database half of §100.51 and §100.52).
--
-- The in-app agent and the notifications need three things from the database, and nothing else:
--
--   1. WHICH MODEL MAY READ WHAT, per organization: `core.model_routing_policy`. One column that
--      matters, `provider_ceiling`: the highest classification of content that may leave the host,
--      to a provider's model or in a notification. `none`, `public` or `internal`, and never
--      `confidential` or `restricted` — the database refuses those in every session, an
--      administrator's included (KF-ROUTE-001), because ADR 0040 decision 8 is not a default an
--      organization may change: confidential and restricted content is answered on the host or
--      not at all. No row means `internal`, ADR 0040's default; whether any provider is reachable
--      at all is the deployment's (a key, or none). Written only by `set_model_routing_policy`
--      (KF-ROUTE-002), which is institutional, so no agent can widen what reaches a provider.
--      Append-only; the highest revision per organization is in force.
--
--   2. A PERSON'S OWN NOTIFICATION SETTING: `core.notification_preference`, per person and
--      organization: the daily digest `daily` (also what no row means) or `off`, and the urgent
--      push `urgent` (no row) or `off`. Quiet by default is the shape, not a setting: nothing but
--      an urgent item is ever pushed. Written only by `set_notification_preference`, for the
--      person who performs it and never by an agent acting for them (KF-NOTIFY-001, KF-NOTIFY-002).
--
--   3. WHAT A NOTIFICATION MAY SAY, decided here: `core.needs_you_digest()` and
--      `core.urgent_notifications(since)`, security definer, executable by `kf_notifier` alone.
--      The notifier login reads no table. It receives, per person, the items Needs you would list
--      for them (the same three lists, the same read grants and clearance), and for each item a
--      title and identifier ONLY when the item's classification is at or below its organization's
--      provider ceiling; everything else arrives as a row with no title and no identifier, which
--      the digest renders as a count and a link (KF-SAS-RQ-274). The urgent function returns no
--      title at all: a push says that something needs the person, and nothing about what.
--
-- THE GUARDS THIS INHERITS. Both new tables: row security enabled and forced, every policy's
-- context function wrapped as `(select …)`, the act write guard (core.install_action_context_guards),
-- a kf_backup read policy, an export section, and a declared exemption from the master-record input
-- triggers. Neither is transient (§64B): a routing decision and a person's notification setting are
-- records of decisions, exported and restored. The chat keeps nothing (KF-WAR-0006; ADR 0040): no
-- table here holds a question or an answer.

